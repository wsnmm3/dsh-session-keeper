/**
 * Rebuilds both faces of the plugin and the generated Remote manifest.
 *
 * The plugin has three build products that have to agree with each other:
 * the Web client bundle, the Host service modules, and the typert manifest
 * that tells the client which Remote methods exist. Running them in the wrong
 * order — or forgetting the last step — produces a plugin that loads but
 * cannot call its own new methods, so this script owns the sequence.
 *
 * Run: node scripts/build-all.mjs
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const lib = path.join(root, 'lib')

/**
 * Run one step, failing loudly on a non-zero exit.
 *
 * `shell` stays off: this machine's Node lives under `C:\Program Files`, and a
 * shell would split that path on its space before the program ever starts.
 * Only the `npx` steps ask for a shell, and those resolve through PATH.
 */
function run(label, command, args, options = {}) {
  process.stdout.write(`\n=== ${label} ===\n`)
  execFileSync(command, args, { cwd: root, stdio: 'inherit', ...options })
}

// The Host build and the client build both write into `lib/`, and the manifest
// injection rewrites a file the Host build does not produce, so the order is:
// compile both faces, fold the CSS into the client bundle, then inject.
//
// `npx` is a `.cmd` shim on Windows, so those two steps need a shell; every
// step that runs `node` itself goes through `process.execPath` with no shell,
// which keeps this machine's space-bearing Node path intact.
run('host face', 'npx', ['tsdown', '--config', 'tsdown.host.config.ts'], { shell: true })
run('client face', 'npx', ['tsdown'], { shell: true })
run('inline css', process.execPath, [path.join('scripts', 'inline-css.mjs')])

// The typert manifest is generated by the upstream monorepo's generator, which
// this repository does not carry, so the descriptors for the hand-authored
// recycle methods are injected here instead.
//
// The Host build emits `lib/index.js` while the manifest lives beside it in
// the installed package; when building straight into `lib/` the manifest is
// absent, so fall back to the copy checked into this build tree.
const manifest = path.join(lib, 'typert.remote-client.js')
if (!fs.existsSync(manifest)) {
  const seed = path.join(root, 'seed', 'typert.remote-client.js')
  if (fs.existsSync(seed)) {
    fs.copyFileSync(seed, manifest)
    console.log(`\nseeded lib/typert.remote-client.js from ${path.relative(root, seed)}`)
  }
}
if (fs.existsSync(manifest)) run('inject recycle descriptors', process.execPath, [path.join('scripts', 'inject-recycle-descriptors.mjs')])
else console.log('\nno typert manifest in lib/; skipping descriptor injection')

run('verify client bundle', process.execPath, [path.join('scripts', 'verify-build.cjs')])
if (fs.existsSync(manifest)) run('verify typert manifest', process.execPath, [path.join('scripts', 'verify-typert-manifest.mjs')])
run('recycle unit tests', process.execPath, [path.join('scripts', 'test-recycle.mjs')])

console.log('\nBUILD_ALL_DONE')
